package com.chavaillaz.fx.islands.workbench;

/**
 * Where the main menu of a {@link Workbench} stands.
 */
public enum MainMenuPlacement {

    /**
     * Where the operating system puts the menus of its applications: in its menu bar on macOS, and elsewhere in a menu
     * opened by the first button of the main toolbar.
     */
    SYSTEM,

    /**
     * In a menu opened by the first button of the main toolbar, on every operating system, macOS included.
     */
    MAIN_TOOLBAR
}
